static int has(const Range *r, size_t n, uint32_t c)
{
    size_t l = 0;
    while (l < n) {
        size_t m = l + (n - l) / 2;
        if (c < r[m].lo)
            n = m;
        else if (c > r[m].hi)
            l = m + 1;
        else
            return 1;
    }
    return 0;
}
static size_t escape(const unsigned char *s, size_t n, size_t i)
{
    size_t j = i;
    if (s[i] == 0x9b) {
        j = i + 1;
        goto csi;
    }
    if (s[i] != 27)
        return i;
    if (++j >= n)
        return j;
    if (s[j] == '[') {
        j++;
    csi:
        while (j < n) {
            unsigned c = s[j++];
            if (c >= 0x40 && c <= 0x7e)
                break;
        }
        return j;
    }
    if (s[j] == ']' || s[j] == 'P' || s[j] == '_' || s[j] == '^') {
        j++;
        while (j < n) {
            if (s[j++] == 7)
                break;
            if (j < n && s[j - 1] == 27 && s[j] == '\\') {
                j++;
                break;
            }
        }
        return j;
    }
    while (j < n && s[j] >= 0x20 && s[j] <= 0x2f)
        j++;
    if (j < n)
        j++;
    return j;
}
static uint32_t decode(const unsigned char *s, size_t n, size_t *i)
{
    unsigned c = s[(*i)++];
    if (c < 128)
        return c;
    unsigned k = c < 224 ? 1 : c < 240 ? 2 : 3;
    c &= k == 1 ? 31 : k == 2 ? 15 : 7;
    while (k-- && *i < n)
        c = (c << 6) | (s[(*i)++] & 63);
    return c;
}
static JSValue strip(JSContext *ctx, JSValueConst self, int argc, JSValueConst *argv)
{
    size_t n;
    const char *s = JS_ToCStringLen(ctx, &n, argv[0]);
    if (!s)
        return JS_EXCEPTION;
    char *out = js_malloc(ctx, n + 1);
    if (!out) {
        JS_FreeCString(ctx, s);
        return JS_EXCEPTION;
    }
    size_t o = 0;
    for (size_t i = 0; i < n;) {
        size_t j = escape((const unsigned char *)s, n, i);
        if (j != i)
            i = j;
        else
            out[o++] = s[i++];
    }
    JSValue v = JS_NewStringLen(ctx, out, o);
    js_free(ctx, out);
    JS_FreeCString(ctx, s);
    return v;
}
static JSValue width(JSContext *ctx, JSValueConst self, int argc, JSValueConst *argv)
{
    size_t n;
    const unsigned char *s = (const unsigned char *)JS_ToCStringLen(ctx, &n, argv[0]);
    if (!s)
        return JS_EXCEPTION;
    int count = argc > 1 ? JS_ToBool(ctx, argv[1]) : 0,
        narrow = argc > 2 ? JS_ToBool(ctx, argv[2]) : 1;
    int total = 0, last = 0, join = 0, ri = 0;
    for (size_t i = 0; i < n;) {
        if (!count) {
            size_t j = escape(s, n, i);
            if (j != i) {
                i = j;
                continue;
            }
        }
        uint32_t c = decode(s, n, &i);
        if (c == 0x200d) {
            join = 1;
            continue;
        }
        if (c == 0xfe0f || c == 0x20e3) {
            if (last == 1) {
                total++;
                last = 2;
            }
            continue;
        }
        if (c >= 0x1f3fb && c <= 0x1f3ff)
            continue;
        if ((c >= 0x1160 && c <= 0x11ff) || has(zero, countof(zero), c))
            continue;
        if (c < 32 || (c >= 127 && c < 160))
            continue;
        int w = has(wide, countof(wide), c) || (!narrow && has(ambiguous, countof(ambiguous), c))
                    ? 2
                    : 1;
        if (c >= 0x1f1e6 && c <= 0x1f1ff) {
            if (ri) {
                ri = 0;
                continue;
            }
            ri = 1;
            w = 2;
        } else
            ri = 0;
        if (join) {
            if (w > last) {
                total += w - last;
                last = w;
            }
            join = 0;
        } else {
            total += w;
            last = w;
        }
    }
    JS_FreeCString(ctx, (const char *)s);
    return JS_NewInt32(ctx, total);
}
static JSValue html(JSContext *ctx, JSValueConst self, int argc, JSValueConst *argv)
{
    size_t n;
    const char *s = JS_ToCStringLen(ctx, &n, argv[0]);
    if (!s)
        return JS_EXCEPTION;
    if (n > (SIZE_MAX - 1) / 6) {
        JS_FreeCString(ctx, s);
        return JS_ThrowOutOfMemory(ctx);
    }
    char *out = js_malloc(ctx, n * 6 + 1);
    if (!out) {
        JS_FreeCString(ctx, s);
        return JS_EXCEPTION;
    }
    size_t o = 0;
    for (size_t i = 0; i < n; i++) {
        const char *r = NULL;
        switch (s[i]) {
        case '&':
            r = "&amp;";
            break;
        case '<':
            r = "&lt;";
            break;
        case '>':
            r = "&gt;";
            break;
        case '"':
            r = "&quot;";
            break;
        case 39:
            r = "&#x27;";
            break;
        }
        if (r) {
            size_t z = strlen(r);
            memcpy(out + o, r, z);
            o += z;
        } else
            out[o++] = s[i];
    }
    JSValue v = JS_NewStringLen(ctx, out, o);
    js_free(ctx, out);
    JS_FreeCString(ctx, s);
    return v;
}
