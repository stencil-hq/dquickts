"""sys.settrace / sys.setprofile event streams (CPython 3.15 legacy tracing).

Expected output: test_trace.out, generated by python3.15:
    python3.15 tests/py/trace/test_trace.py > tests/py/trace/test_trace.out
"""
import sys

BASE = sys._getframe().f_code.co_firstlineno


def fmt_arg(event, arg):
    if event == 'exception':
        return '%s(%s)' % (arg[0].__name__, arg[1])
    if event in ('c_call', 'c_return', 'c_exception'):
        return getattr(arg, '__qualname__', getattr(arg, '__name__', '?'))
    if event == 'return':
        if callable(arg):
            return '<%s>' % arg.__qualname__
        return repr(arg)
    return ''


EVENTS = []


def record(frame, event, arg):
    EVENTS.append('%-9s %-12s %3d %s' % (event, frame.f_code.co_name,
                                         frame.f_lineno - BASE, fmt_arg(event, arg)))


def tracer(frame, event, arg):
    record(frame, event, arg)
    return tracer


def run(title, func, *args, trace=tracer, profile=None):
    del EVENTS[:]
    if profile is not None:
        sys.setprofile(profile)
    else:
        sys.settrace(trace)
    try:
        result = func(*args)
    except Exception as e:
        result = 'raised %s(%s)' % (type(e).__name__, e)
    finally:
        sys.settrace(None)
        sys.setprofile(None)
    print('==', title, '->', result)
    for e in EVENTS:
        if ' run ' in e:
            continue
        print('  ', e)


# ---- calls, lines, returns -------------------------------------------------

def add(a, b):
    c = a + b
    return c


def calls():
    x = add(1, 2)
    y = add(x,
            3)
    return add(x, y)


run('calls', calls)


def one_liner(): return 42


def uses_one_liner():
    return one_liner() + one_liner()


run('one-liner', uses_one_liner)


def recurse(n):
    if n <= 0:
        return 0
    return n + recurse(n - 1)


run('recursion', recurse, 2)

# ---- loops -------------------------------------------------------------------


def loops():
    total = 0
    for i in range(3):
        if i == 1:
            continue
        total += i
    j = 0
    while j < 2:
        j += 1
    while j < 4: j += 1
    for k in range(5):
        if k == 2:
            break
    else:
        total = -1
    for m in []:
        pass
    else:
        total += 100
    return total


run('loops', loops)


def nested_loops():
    s = 0
    for a in range(2):
        for b in range(2):
            s += a * b
    return s


run('nested loops', nested_loops)


def comprehensions():
    xs = [i * i for i in range(3)]
    d = {k: v for k, v in zip('ab', xs)}
    g = sum(x for x in xs)
    return xs, d, g


run('comprehensions', comprehensions)

# ---- generators ---------------------------------------------------------------


def gen(n):
    for i in range(n):
        yield i
    return 'done'


def use_gen():
    out = []
    for v in gen(2):
        out.append(v)
    return out


run('generator for', use_gen)


def counter():
    total = 0
    while True:
        x = yield total
        if x is None:
            break
        total += x
    return total


def use_send():
    c = counter()
    next(c)
    c.send(5)
    c.send(7)
    try:
        c.send(None)
    except StopIteration as e:
        return e.value


run('generator send', use_send)


def closing():
    try:
        yield 1
        yield 2
    finally:
        print('closing finally')


def use_close():
    g = closing()
    next(g)
    g.close()
    return 'closed'


run('generator close', use_close)


def thrower():
    try:
        yield 1
    except ValueError as e:
        yield 'caught %s' % e


def use_throw():
    g = thrower()
    next(g)
    r = g.throw(ValueError('boom'))
    g.close()
    return r


run('generator throw', use_throw)


def delegate():
    r = yield from gen(2)
    return r


def use_delegate():
    return list(delegate())


run('yield from', use_delegate)

# ---- exceptions ----------------------------------------------------------------


def fails(x):
    if x:
        raise KeyError(x)
    return x


def exceptions():
    try:
        1 / 0
    except ZeroDivisionError:
        pass
    try:
        fails('k')
    except KeyError as e:
        r = str(e)
    try:
        try:
            fails('inner')
        finally:
            r += '!'
    except KeyError:
        r += '?'
    return r


run('exceptions', exceptions)


def uncaught():
    return fails('out')


run('uncaught', uncaught)


def reraise():
    try:
        fails('again')
    except KeyError:
        raise


run('reraise', reraise)


def with_stmt():
    class CM:
        def __enter__(self):
            return 'cm'

        def __exit__(self, *exc):
            return False

    with CM() as v:
        w = v + '!'
    return w


run('with', with_stmt)

# ---- local trace functions ------------------------------------------------------


def local_tracer(frame, event, arg):
    record(frame, 'L:' + event, arg)
    return local_tracer


def selective(frame, event, arg):
    record(frame, event, arg)
    if frame.f_code.co_name == 'add':
        return local_tracer
    if frame.f_code.co_name == 'fails':
        return None
    return selective


def local_main():
    a = add(1, 1)
    try:
        fails(1)
    except KeyError:
        pass
    return a


run('local tracers', local_main, trace=selective)


def returns_none_later(frame, event, arg):
    record(frame, event, arg)
    if event == 'call':
        return returns_none_later
    return None     # keeps f_trace (CPython trace_trampoline)


run('local returns None', calls, trace=returns_none_later)


def no_lines(frame, event, arg):
    record(frame, event, arg)
    if event == 'call' and frame.f_code.co_name == 'add':
        frame.f_trace_lines = False
    return no_lines


run('f_trace_lines=False', calls, trace=no_lines)


def switcher(frame, event, arg):
    record(frame, event, arg)
    if event == 'line' and frame.f_code.co_name == 'calls':
        frame.f_trace = local_tracer
    return switcher


run('frame.f_trace assignment', calls, trace=switcher)


def frame_info(frame, event, arg):
    if event == 'call' and frame.f_code.co_name == 'add':
        back = frame.f_back
        EVENTS.append('add called from %s line %d, locals %s, back is back %s' % (
            back.f_code.co_name, back.f_lineno - BASE, sorted(frame.f_locals.items()),
            back is frame.f_back))
    if event == 'return' and frame.f_code.co_name == 'add':
        EVENTS.append('add returns with locals %s' % sorted(frame.f_locals.items()))
    return frame_info


run('frame attributes', calls, trace=frame_info)


