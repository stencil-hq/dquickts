# Numeric builtins: abs, divmod, round, pow, sum, min/max with numbers, bin/hex/oct, int().


def check(label, func):
    try:
        print(label, repr(func()))
    except Exception as e:
        print(label, "->", type(e).__name__ + ":", e)


check("abs int", lambda: abs(-7))
check("abs float", lambda: abs(-2.5))
check("abs neg zero", lambda: abs(-0.0))
check("abs complex", lambda: abs(3 - 4j))
check("abs bool", lambda: abs(True))
check("abs big", lambda: abs(-(10**30)))
check("abs str", lambda: abs("x"))

check("divmod pos", lambda: divmod(17, 5))
check("divmod neg num", lambda: divmod(-17, 5))
check("divmod neg den", lambda: divmod(17, -5))
check("divmod both neg", lambda: divmod(-17, -5))
check("divmod float", lambda: divmod(7.5, 2))
check("divmod neg float", lambda: divmod(-7.5, 2))
check("divmod zero", lambda: divmod(1, 0))
check("divmod float zero", lambda: divmod(1.0, 0.0))
check("divmod complex", lambda: divmod(1j, 1))

check("round half even 0.5", lambda: round(0.5))
check("round half even 1.5", lambda: round(1.5))
check("round half even 2.5", lambda: round(2.5))
check("round neg half", lambda: round(-0.5))
check("round neg 1.5", lambda: round(-1.5))
check("round ndigits", lambda: round(3.14159, 2))
check("round repr issue", lambda: round(2.675, 2))
check("round ndigits zero", lambda: round(2.5, 0))
check("round neg ndigits int", lambda: round(1250, -2))
check("round neg ndigits int2", lambda: round(1350, -2))
check("round neg ndigits float", lambda: round(1234.5, -2))
check("round int ndigits None", lambda: round(7, None))
check("round int positive ndigits", lambda: round(7, 3))
check("round inf", lambda: round(float("inf")))
check("round nan", lambda: round(float("nan")))
check("round str", lambda: round("1"))

check("pow int", lambda: pow(2, 10))
check("pow negative exp", lambda: pow(2, -2))
check("pow mod", lambda: pow(3, 200, 7))
check("pow inverse", lambda: pow(3, -1, 7))
check("pow no inverse", lambda: pow(2, -1, 4))
check("pow mod zero", lambda: pow(2, 3, 0))
check("pow float mod", lambda: pow(2.0, 3, 5))
check("pow neg fractional type", lambda: type(pow(-8, 0.5)).__name__)
check("pow zero zero", lambda: (pow(0, 0), pow(0.0, 0), 0.0**0.0))
check("pow float exact", lambda: (pow(2.0, 10), pow(4, 0.5), pow(2, -1.0)))
check("pow kwargs", lambda: pow(base=2, exp=5, mod=3))
check("pow big", lambda: pow(7, 77) % 1000)

check("sum ints", lambda: sum([1, 2, 3]))
check("sum start", lambda: sum([1, 2, 3], 10))
check("sum start kw", lambda: sum(range(4), start=100))
check("sum floats", lambda: sum([0.1] * 10))
check("sum mixed", lambda: sum([1, 2.5, True]))
check("sum lists", lambda: sum([[1], [2, 3]], []))
check("sum tuples", lambda: sum([(1,), (2,)], ()))
check("sum strings", lambda: sum(["a", "b"], ""))
check("sum bytes", lambda: sum([b"a"], b""))
check("sum empty", lambda: sum([]))
check("sum complex", lambda: sum([1j, 2, 0.5]))

check("bin", lambda: (bin(0), bin(5), bin(-5), bin(2**40)))
check("hex", lambda: (hex(0), hex(255), hex(-255), hex(2**64)))
check("oct", lambda: (oct(0), oct(8), oct(-8)))
check("bin float", lambda: bin(1.5))
check("hex str", lambda: hex("1"))
check("int from bases", lambda: (int("ff", 16), int("0x1f", 0), int("0b101", 0), int("z", 36), int("  -12  ")))
check("int underscores", lambda: int("1_000"))
check("int bad base", lambda: int("1", 1))
check("int base with non-str", lambda: int(5, 10))
check("int float trunc", lambda: (int(3.9), int(-3.9), int(True)))
check("float parse", lambda: (float("1e3"), float("-inf"), float(" 2.5 "), float("1_0.5")))
check("min max numbers", lambda: (min(3, 1, 2), max(3, 1.5), max(-0.0, 0.0), min(0, False)))
check("bool arithmetic", lambda: (True + True, True * 3, -True, True / 2))
