"""L0 golden: inf, -inf, nan and signed zero.

Covers creation, repr, comparisons (nan is unordered and unequal to itself),
arithmetic propagation, identity vs equality in containers, and -0.0.

Usage: python3.15 -I -X utf8 tests/py/golden/types/016_float_special.py
"""


def show(label: str, thunk) -> None:
    """Print label and repr(thunk()), or the exception type and message."""
    try:
        print(label, repr(thunk()))
    except Exception as e:
        print(label, type(e).__name__, str(e))


