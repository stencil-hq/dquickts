"""L0 golden: bytes methods.

Covers split/rsplit/splitlines, strip family, replace, startswith/endswith,
find/index/count (with int arguments), hex/fromhex, decode, join, case
methods (ASCII only), partition, padding, predicates and errors.

Usage: python3.15 -I -X utf8 tests/py/golden/types/037_bytes_methods.py
"""


def show(label: str, thunk) -> None:
    """Print label and repr(thunk()), or the exception type and message."""
    try:
        print(label, repr(thunk()))
    except Exception as e:
        print(label, type(e).__name__, str(e))


show("split()", lambda: b"  a b\tc\n ".split())
show("split ws ascii only", lambda: b"a\xa0b\x85c".split())
show("split sep", lambda: b"a,b,,c".split(b","))
show("split maxsplit", lambda: b"a,b,c".split(b",", 1))
show("rsplit maxsplit", lambda: b"a,b,c".rsplit(b",", 1))
show("split empty sep", lambda: b"abc".split(b""))
show("split str sep", lambda: b"a,b".split(","))
show("split int sep", lambda: b"a,b".split(44))
show("split bytearray sep", lambda: b"a,b".split(bytearray(b",")))
show("strip", lambda: b"  \t\nab \x0b\x0c\r".strip())
show("strip high ws", lambda: b"\xa0ab\xa0".strip())
show("strip chars", lambda: b"xxabyx".strip(b"xy"))
show("lstrip", lambda: b"  ab ".lstrip())
show("rstrip chars", lambda: b"ab\r\n".rstrip(b"\r\n"))
show("strip str chars", lambda: b"ab".strip("a"))
show("replace", lambda: b"a-b-c".replace(b"-", b"+"))
show("replace count", lambda: b"a-b-c".replace(b"-", b"", 1))
show("replace empty", lambda: b"ab".replace(b"", b"."))
show("replace str", lambda: b"ab".replace("a", "b"))
show("startswith", lambda: b"hello".startswith(b"he"))
show("startswith tuple", lambda: b"hello".startswith((b"x", b"hel")))
show("endswith range", lambda: b"hello".endswith(b"ll", 0, 4))
show("startswith str", lambda: b"hello".startswith("h"))
show("find", lambda: b"hello".find(b"l"))
show("find int", lambda: b"hello".find(108))
show("rfind int", lambda: b"hello".rfind(108))
show("find int range", lambda: b"hello".find(108, 4))
show("find bad int", lambda: b"hello".find(256))
show("find str", lambda: b"hello".find("l"))
show("index missing", lambda: b"hello".index(b"z"))
show("rindex int missing", lambda: b"hello".rindex(122))
show("count", lambda: b"aaaa".count(b"aa"))
show("count int", lambda: b"banana".count(97))
show("count empty", lambda: b"abc".count(b""))
show("hex", lambda: b"\x00\xab\xff".hex())
show("hex sep", lambda: b"\x01\x02\x03\x04".hex(":"))
show("hex sep bytes_per_sep", lambda: b"\x01\x02\x03\x04\x05".hex("-", 2))
show("hex sep negative", lambda: b"\x01\x02\x03\x04\x05".hex("-", -2))
show("hex empty", lambda: b"".hex())
show("hex bad sep", lambda: b"\x01\x02".hex("ab"))
show("fromhex", lambda: bytes.fromhex("00ab FF"))
show("fromhex empty", lambda: bytes.fromhex(""))
show("fromhex whitespace", lambda: bytes.fromhex(" \t0a\n0b "))
show("fromhex odd", lambda: bytes.fromhex("abc"))
show("fromhex bad", lambda: bytes.fromhex("zz"))
show("fromhex split byte", lambda: bytes.fromhex("a b"))
show("fromhex bytes arg", lambda: bytes.fromhex(b"ab"))
show("decode", lambda: b"caf\xc3\xa9".decode())
show("decode errors replace", lambda: b"caf\xe9".decode("utf-8", "replace"))
show("decode latin-1", lambda: b"caf\xe9".decode("latin-1"))
show("decode strict", lambda: b"caf\xe9".decode())
show("join", lambda: b", ".join([b"a", bytearray(b"b"), memoryview(b"c")]))
show("join type", lambda: type(b"".join([bytearray(b"x")])).__name__)
show("join str", lambda: b",".join([b"a", "b"]))
show("join int", lambda: b",".join([1]))
show("upper", lambda: b"abc\xe9xyz".upper())
show("lower", lambda: b"ABC\xc9".lower())
show("title", lambda: b"hello world".title())
show("capitalize", lambda: b"hELLO".capitalize())
show("swapcase", lambda: b"aBc".swapcase())
show("partition", lambda: b"k=v=w".partition(b"="))
show("rpartition", lambda: b"k=v=w".rpartition(b"="))
show("center", lambda: b"ab".center(6, b"*"))
show("ljust", lambda: b"ab".ljust(4))
show("rjust fill str", lambda: b"ab".rjust(4, "*"))
show("zfill", lambda: b"-5".zfill(4))
show("expandtabs", lambda: b"a\tb".expandtabs(4))
show("removeprefix", lambda: b"prefix-x".removeprefix(b"prefix-"))
show("removesuffix", lambda: b"x.txt".removesuffix(b".txt"))
show("isdigit", lambda: (b"123".isdigit(), b"\xb2".isdigit(), b"".isdigit()))
show("isalpha", lambda: (b"abc".isalpha(), b"\xe9".isalpha()))
show("isspace", lambda: (b" \t\n\r\x0b\x0c".isspace(), b"\x1c".isspace()))
show("isascii", lambda: (b"abc".isascii(), b"\x80".isascii(), b"".isascii()))
show("isupper/islower", lambda: (b"ABC1".isupper(), b"abc1".islower(), b"1".islower()))
show("istitle", lambda: (b"Hello World".istitle(), b"Hello world".istitle()))
show("isalnum", lambda: (b"a1".isalnum(), b"a_1".isalnum()))
show("bytes has no encode", lambda: b"x".encode())
show("bytes has no format", lambda: b"{}".format(1))
