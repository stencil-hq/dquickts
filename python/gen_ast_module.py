#! /usr/bin/env python3
"""Generate python/mod_ast.c, the `_ast` module of dquickts Python.

Port of the Python-object side of CPython's Parser/asdl_c.py
(Python/Python-ast.c: the AST node classes, ast2obj / obj2ast) together
with Python/ast.c (_PyAST_Validate) and Python/ast_preprocess.c
(_PyAST_Preprocess, used by compile(..., PyCF_ONLY_AST)) (PSF-2.0).

The node classes are described by tables generated from the ASDL
description (one entry per class, one per field); the conversions are
generic interpreters over those tables and the C node layout of
python/ast.h (offsetof).  The hand-written runtime below (RUNTIME) is
emitted verbatim after the tables.

Usage (from the repository root; deterministic, re-runnable):
    python3.15 python/gen_ast_module.py cpython/Parser/Python.asdl python/mod_ast.c
"""

import argparse
import sys
from pathlib import Path


def import_cpython_asdl(parser_dir):
    """Import CPython's asdl and asdl_c modules from parser_dir."""
    sys.path.insert(0, str(parser_dir))
    sys.dont_write_bytecode = True    # leave the CPython checkout untouched
    try:
        import asdl
        import asdl_c
    finally:
        sys.path.pop(0)
    return asdl, asdl_c


AUTOGEN = (
    "// File automatically generated by python/gen_ast_module.py from {}.\n"
    "// Do not edit: regenerate with\n"
    "//   python3.15 python/gen_ast_module.py cpython/Parser/Python.asdl python/mod_ast.c\n"
)

HEADER = r"""/*
 * The _ast module: AST node classes and the conversions between Python AST
 * objects and the C AST of python/ast.h.
 *
 * Derived from CPython Parser/asdl_c.py and Python/Python-ast.c (node
 * classes, ast2obj, obj2ast), Python/ast.c (_PyAST_Validate) and
 * Python/ast_preprocess.c (_PyAST_Preprocess) (PSF-2.0), v3.15.2.
 *
 * Entry points (static, one translation unit with quickjs.c):
 *   qp_ast_check(ctx, obj)                  PyAST_Check: 1 / 0 / -1
 *   qp_ast2obj(ctx, mod)                    PyAST_mod2obj
 *   qp_obj2ast(ctx, obj, arena, mode)       PyAST_obj2mod (mode 0 exec,
 *                                           1 eval, 2 single, 3 func_type)
 *   qp_ast_validate(ctx, mod)               _PyAST_Validate: 1 ok / 0 error
 *   qp_ast_preprocess(ctx, mod, filename, flags, optimize, arena,
 *                     syntax_check_only)    _PyCompile_AstPreprocess
 * Errors are pending Python exceptions.  Identifiers are JSAtoms (owned by
 * the arena), constants qp_const (QP_CONST_OBJECT for the Python constant
 * values the parser never produces: tuple, frozenset, complex with a real
 * part, and the invalid types _PyAST_Validate rejects).
 *
 * The per-context state (CPython struct ast_state) is the tuple
 * QPModState.ast_state: the node classes indexed by QPAST_T_*, then the
 * singleton instances of the operator/context classes, then the set of
 * abstract classes.  It is created on first use (compile() may need it
 * before `_ast` is imported, like CPython's get_ast_state()).
 */
"""

TABLE_TYPES = r"""
/* ---- generated tables ---------------------------------------------------- */

/* Field types: builtin ASDL types (negative) or a QPAST_T_* class. */
#define QPAST_B_IDENTIFIER (-1)
#define QPAST_B_STRING     (-2)
#define QPAST_B_INT        (-3)
#define QPAST_B_CONSTANT   (-4)

#define QPAST_F_SEQ 0x01        /* T* */
#define QPAST_F_OPT 0x02        /* T? */

typedef struct QPAstField {
    uint16_t name;              /* QPAST_N_* */
    int16_t type;               /* QPAST_B_* or QPAST_T_* */
    uint8_t flags;              /* QPAST_F_* */
    uint16_t offset;            /* offset of the field in the C node struct */
    int16_t dflt;               /* optional int attribute: offset of the attribute
                                   giving its default (end_lineno <- lineno,
                                   end_col_offset <- col_offset), -1 = 0 */
} QPAstField;

enum {
    QPAST_K_BASE,               /* ast.AST */
    QPAST_K_SUM,                /* abstract class of a sum type (stmt, expr, ...) */
    QPAST_K_SIMPLE_SUM,         /* abstract class of a simple sum (operator, ...) */
    QPAST_K_CONS,               /* constructor of a sum (BinOp, ...) */
    QPAST_K_SIMPLE_CONS,        /* constructor of a simple sum (Add, ...): singleton */
    QPAST_K_PRODUCT,            /* product type (arguments, keyword, ...) */
};

typedef struct QPAstTypeDesc {
    const char *name;
    const char *doc;            /* asdl_of() text, the class __doc__ */
    int16_t base;               /* QPAST_T_* of the Python base class (-1 for AST) */
    uint8_t kind;               /* QPAST_K_* */
    uint8_t nfields, nattrs;
    uint16_t fields, attrs;     /* first entries in qpast_fields */
    int16_t sum;                /* constructors: their sum; sums: first constructor */
    uint8_t ncons;              /* sums: number of constructors */
    int value;                  /* constructors: the C kind (X_kind) / enum value */
    uint16_t size;              /* sums, products: size of the C node struct */
    uint16_t kind_offset;       /* sums: offset of the `kind` member */
} QPAstTypeDesc;
"""


def c_string(s):
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


class Gen:
    def __init__(self, asdl, asdl_c, mod):
        self.asdl = asdl
        self.asdl_c = asdl_c
        self.mod = mod
        self.types = []          # (name, kind, base, extra dict)
        self.index = {}
        self.names = []
        self.name_index = {}
        self.fields = []         # emitted field initialisers
        self.simple_sums = set()
        for dfn in mod.dfns:
            if isinstance(dfn.value, asdl.Sum) and asdl_c.is_simple(dfn.value):
                self.simple_sums.add(dfn.name)

    def name_id(self, name):
        if name not in self.name_index:
            self.name_index[name] = len(self.names)
            self.names.append(name)
        return self.name_index[name]

    def add_type(self, name, **kw):
        self.index[name] = len(self.types)
        kw["name"] = name
        self.types.append(kw)

    def collect(self):
        asdl, asdl_c = self.asdl, self.asdl_c
        self.add_type("AST", kind="QPAST_K_BASE", base=None, doc=None,
                      fields=[], attrs=[], owner=None)
        for dfn in self.mod.dfns:
            v = dfn.value
            if isinstance(v, asdl.Sum):
                simple = asdl_c.is_simple(v)
                self.add_type(dfn.name, kind="QPAST_K_SIMPLE_SUM" if simple else "QPAST_K_SUM",
                              base="AST", doc=asdl_c.asdl_of(dfn.name, v), fields=[],
                              attrs=list(v.attributes), owner=("sum", dfn.name),
                              cons=[t.name for t in v.types])
                for i, t in enumerate(v.types):
                    self.add_type(t.name, kind="QPAST_K_SIMPLE_CONS" if simple else "QPAST_K_CONS",
                                  base=dfn.name, doc=asdl_c.asdl_of(t.name, t),
                                  fields=list(t.fields), attrs=[],
                                  owner=("cons", dfn.name, t.name),
                                  value=str(i + 1) if simple else "%s_kind" % t.name)
            else:
                self.add_type(dfn.name, kind="QPAST_K_PRODUCT", base="AST",
                              doc=asdl_c.asdl_of(dfn.name, v), fields=list(v.fields),
                              attrs=list(v.attributes), owner=("prod", dfn.name))

    def field_type(self, f):
        builtin = {"identifier": "QPAST_B_IDENTIFIER", "string": "QPAST_B_STRING",
                   "int": "QPAST_B_INT", "constant": "QPAST_B_CONSTANT"}
        if f.type in builtin:
            return builtin[f.type]
        return "QPAST_T_%s" % f.type

    def offset(self, owner, fname, is_attr):
        if owner[0] == "sum":
            return "offsetof(struct _%s, %s)" % (owner[1], fname)
        if owner[0] == "cons":
            return "offsetof(struct _%s, v.%s.%s)" % (owner[1], owner[2], fname)
        return "offsetof(struct _%s, %s)" % (owner[1], fname)

    def emit_fields(self, owner, fields, is_attr):
        start = len(self.fields)
        names = [f.name for f in fields]
        for f in fields:
            flags = []
            if f.seq:
                flags.append("QPAST_F_SEQ")
            if f.opt:
                flags.append("QPAST_F_OPT")
            dflt = "-1"
            src = {"end_lineno": "lineno", "end_col_offset": "col_offset"}.get(f.name)
            if f.opt and f.type == "int" and src in names:
                dflt = self.offset(owner, src, is_attr)
            self.fields.append("    { QPAST_N_%s, %s, %s, %s, %s },"
                               % (f.name, self.field_type(f), "|".join(flags) or "0",
                                  self.offset(owner, f.name, is_attr), dflt))
            self.name_id(f.name)
        return start

    def generate(self, out):
        self.collect()
        type_lines = []
        for t in self.types:
            fstart = self.emit_fields(t["owner"], t["fields"], False) if t["fields"] else 0
            astart = self.emit_fields(t["owner"], t["attrs"], True) if t["attrs"] else 0
            kind = t["kind"]
            base = "QPAST_T_%s" % t["base"] if t["base"] else "-1"
            doc = '"%s"' % c_string(t["doc"]) if t["doc"] is not None else "NULL"
            sum_ = "-1"
            ncons = "0"
            value = "0"
            size = "0"
            kind_offset = "0"
            if kind in ("QPAST_K_SUM", "QPAST_K_SIMPLE_SUM"):
                sum_ = "QPAST_T_%s" % t["cons"][0]
                ncons = str(len(t["cons"]))
                if kind == "QPAST_K_SUM":
                    size = "sizeof(struct _%s)" % t["name"]
                    kind_offset = "offsetof(struct _%s, kind)" % t["name"]
            elif kind in ("QPAST_K_CONS", "QPAST_K_SIMPLE_CONS"):
                sum_ = "QPAST_T_%s" % t["base"]
                value = t["value"]
            elif kind == "QPAST_K_PRODUCT":
                size = "sizeof(struct _%s)" % t["name"]
            type_lines.append(
                '    [QPAST_T_%s] = { "%s", %s, %s, %s, %d, %d, %s, %s, %s, %s, %s, %s, %s },'
                % (t["name"], t["name"], doc, base, kind, len(t["fields"]), len(t["attrs"]),
                   fstart, astart, sum_, ncons, value, size, kind_offset))

        out.write("\nenum {\n")
        for t in self.types:
            out.write("    QPAST_T_%s,\n" % t["name"])
        out.write("    QPAST_T__COUNT\n};\n")
        out.write("\nenum {\n")
        for n in self.names:
            out.write("    QPAST_N_%s,\n" % n)
        out.write("    QPAST_N__COUNT\n};\n")
        out.write("\nstatic const char *const qpast_names[QPAST_N__COUNT] = {\n")
        for n in self.names:
            out.write('    "%s",\n' % n)
        out.write("};\n")
        out.write("\nstatic const QPAstField qpast_fields[] = {\n")
        out.write("\n".join(self.fields) + "\n")
        out.write("    { 0, 0, 0, 0, -1 }\n};\n")
        out.write("\nstatic const QPAstTypeDesc qpast_types[QPAST_T__COUNT] = {\n")
        out.write("\n".join(type_lines) + "\n};\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("input_file", type=Path)
    ap.add_argument("output_file", type=Path)
    args = ap.parse_args()

    asdl, asdl_c = import_cpython_asdl(args.input_file.resolve().parent)
    mod = asdl.parse(str(args.input_file))
    if not asdl.check(mod):
        sys.exit(1)
    origin = "/".join(args.input_file.parts[-2:])
    runtime = (Path(__file__).resolve().parent / "gen_ast_module_runtime.c.in").read_text()
    with args.output_file.open("w", newline="\n") as f:
        f.write(AUTOGEN.format(origin))
        f.write(HEADER)
        f.write(TABLE_TYPES)
        Gen(asdl, asdl_c, mod).generate(f)
        f.write(runtime)
    print(f"{args.output_file} regenerated.")


if __name__ == "__main__":
    main()
