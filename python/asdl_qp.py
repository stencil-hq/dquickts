#! /usr/bin/env python3
"""Generate the dquickts Python AST C code from an ASDL description.

Adapted from CPython Parser/asdl_c.py (PSF-2.0).  It reuses CPython's own
ASDL parser (Parser/asdl.py) and the type/struct/constructor emitters of
Parser/asdl_c.py from the CPython checkout next to the input file, so the
output mirrors Include/internal/pycore_asdl.h + pycore_ast.h and the
constructor part of Python/Python-ast.c, with these substitutions:

- identifier and string are JSAtom (absent optional = JS_ATOM_NULL);
- constant is qp_const *;
- every function is static (the Python front end is one translation unit);
- errors go to the arena's qp_error instead of the Python error indicator.

It also emits ast_json.c, a JSON dumper (harness NODE format) generated from
the same ASDL, and copies the hand-written runtime of python/compat.h (arena,
errors, constants) into ast.c.

Usage (from the repository root):
    python3.15 python/asdl_qp.py cpython/Parser/Python.asdl \\
        --header python/ast.h --source python/ast.c --json python/ast_json.c
"""

