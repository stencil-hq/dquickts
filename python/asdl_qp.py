def c_string(s):
    """Return s as the body of a C string literal (no surrounding quotes)."""
    return s.replace("\\", "\\\\").replace('"', '\\"')


def make_visitors(asdl, asdl_c):
    """Build the emitter classes on top of CPython's asdl_c visitors."""

    class SequenceDefVisitor(asdl_c.SequenceDefVisitor):
        """asdl_<type>_seq typedefs with static constructor prototypes."""

        def emit_sequence_constructor(self, name, depth):
            ctype = asdl_c.get_c_type(name)
            self.emit("""\
typedef struct {
    _ASDL_SEQ_HEAD
    %(ctype)s typed_elements[1];
} asdl_%(name)s_seq;""" % locals(), reflow=False, depth=depth)
            self.emit("", depth)
            self.emit("static __maybe_unused asdl_%(name)s_seq *"
                      "_Py_asdl_%(name)s_seq_new(Py_ssize_t size, "
                      "PyArena *arena);" % locals(), depth)
            self.emit("", depth)

    class PrototypeVisitor(asdl_c.PrototypeVisitor):
        """Static _PyAST_* constructor prototypes."""

        def emit_function(self, name, ctype, args, attrs, union=True):
            args = args + attrs
            if args:
                argstr = ", ".join(["%s %s" % (atype, aname)
                                    for atype, aname, opt in args])
                argstr += ", PyArena *arena"
            else:
                argstr = "PyArena *arena"
            self.emit("static __maybe_unused %s %s(%s);"
                      % (ctype, asdl_c.ast_func_name(name), argstr), False)

    class FunctionVisitor(asdl_c.FunctionVisitor):
        """Static _PyAST_* constructors; required-field errors go to the arena."""

        def emit_function(self, name, ctype, args, attrs, union=True):
            def emit(s, depth=0, reflow=True):
                self.emit(s, depth, reflow)
            argstr = ", ".join(["%s %s" % (atype, aname)
                                for atype, aname, opt in args + attrs])
            if argstr:
                argstr += ", PyArena *arena"
            else:
                argstr = "PyArena *arena"
            self.emit("static %s" % ctype, 0)
            emit("%s(%s)" % (asdl_c.ast_func_name(name), argstr))
            emit("{")
            emit("%s p;" % ctype, 1)
            for argtype, argname, opt in args:
                if not opt and argtype != "int":
                    emit("if (!%s) {" % argname, 1)
                    emit("qp_error_set(qp_arena_error(arena), QP_ERR_VALUE, "
                         "0, 0, 0, 0,", 2)
                    msg = "field '%s' is required for %s" % (argname, name)
                    emit('             "%s");' % msg, 2, reflow=False)
                    emit('return NULL;', 2)
                    emit('}', 1)

            emit("p = (%s)_PyArena_Malloc(arena, sizeof(*p));" % ctype, 1)
            emit("if (!p)", 1)
            emit("return NULL;", 2)
            if union:
                self.emit_body_union(name, args, attrs)
            else:
                self.emit_body_struct(name, args, attrs)
            emit("return p;", 1)
            emit("}")
            emit("")

    class JsonVisitor(asdl_c.EmitVisitor):
        """qp_json_ast_<type> dumpers for every ASDL type."""

        def __init__(self, file, metadata):
            super().__init__(file, metadata)
            self.pending = []

        # -- literal output, merged into one dbuf call per run --
        def lit(self, s):
            self.pending.append(s)

        def flush(self, depth):
            text = "".join(self.pending)
            self.pending = []
            if not text:
                return
            if len(text) == 1:
                ch = "\\'" if text == "'" else c_string(text)
                self.emit("dbuf_putc(out, '%s');" % ch, depth, False)
            else:
                self.emit('dbuf_putstr(out, "%s");' % c_string(text),
                          depth, False)

        def emit_attributes_and_close(self, attrs, ptr, depth):
            """Close the object, writing the int attributes of ptr first."""
            if not attrs:
                self.lit("}")
                self.flush(depth)
                return
            fmt = "".join(self.pending)
            self.pending = []
            for a in attrs:
                assert str(a.type) == "int", a
                fmt += ',"%s":%%d' % a.name
            fmt += "}"
            vals = ", ".join("%s->%s" % (ptr, a.name) for a in attrs)
            self.emit('dbuf_printf(out, "%s", %s);' % (c_string(fmt), vals),
                      depth, False)

        def ctype(self, name):
            return asdl_c.get_c_type(name)

        def is_simple(self, name):
            return name in self.metadata.simple_sums

        def scalar(self, expr, ftype, tagged, depth):
            self.flush(depth)
            if ftype == "int":
                self.emit('dbuf_printf(out, "%%d", %s);' % expr, depth, False)
                return
            if ftype in ("identifier", "string"):
                call = "qp_json_put_atom(ctx, out, %s)" % expr
            elif ftype == "constant":
                call = "qp_json_put_const(ctx, out, %s, %d)" % (
                    expr, 1 if tagged else 0)
            elif ftype in asdl.builtin_types:
                raise ValueError("unsupported builtin type %r" % ftype)
            else:
                call = "qp_json_ast_%s(ctx, out, %s)" % (ftype, expr)
            self.emit("if (%s < 0)" % call, depth, False)
            self.emit("return -1;", depth + 1)

        def field(self, f, expr, tagged, first, depth):
            assert f.name is not None, f
            self.lit('%s"%s":' % ("" if first else ",", f.name))
            ftype = str(f.type)
            if not f.seq:
                self.scalar(expr, ftype, tagged, depth)
                return
            self.lit("[")
            self.flush(depth)
            self.emit("for (i = 0; i < asdl_seq_LEN(%s); i++) {" % expr,
                      depth, False)
            self.emit("if (i)", depth + 1)
            self.emit("dbuf_putc(out, ',');", depth + 2)
            elem = "asdl_seq_GET(%s, i)" % expr
            if self.is_simple(ftype):
                elem = "(%s)%s" % (self.ctype(ftype), elem)
            self.scalar(elem, ftype, tagged, depth + 1)
            self.emit("}", depth)
            self.lit("]")

        def object_fields(self, tname, fields, prefix, depth):
            self.lit('{"_type":"%s"' % tname)
            for f in fields:
                tagged = (tname, f.name) in TAGGED_CONSTANT_FIELDS
                self.field(f, "%s%s" % (prefix, f.name), tagged, False, depth)

        def prototype(self, name):
            self.emit("static int qp_json_ast_%s(JSContext *ctx, DynBuf *out, "
                      "%s o);" % (name, self.ctype(name)), 0)

        def function_head(self, name, uses_seq):
            self.emit("static int", 0)
            self.emit("qp_json_ast_%s(JSContext *ctx, DynBuf *out, %s o)"
                      % (name, self.ctype(name)), 0)
            self.emit("{", 0)
            if uses_seq:
                self.emit("Py_ssize_t i;", 1)
                self.emit("", 0)

        def null_guard(self):
            self.emit("if (!o) {", 1)
            self.emit('dbuf_putstr(out, "null");', 2)
            self.emit("return 0;", 2)
            self.emit("}", 1)

        def visitModule(self, mod):
            for dfn in mod.dfns:
                self.prototype(dfn.name)
            self.emit("", 0)
            for dfn in mod.dfns:
                self.visit(dfn)

        def visitType(self, type):
            self.visit(type.value, type.name)

        def visitSum(self, sum, name):
            if self.is_simple(name):
                self.function_head(name, False)
                self.emit("switch (o) {", 1)
                for t in sum.types:
                    self.emit("case %s:" % t.name, 1)
                    self.lit('{"_type":"%s"}' % t.name)
                    self.flush(2)
                    self.emit("break;", 2)
                self.emit("default:", 1)
                self.emit('dbuf_putstr(out, "null");', 2)
                self.emit("break;", 2)
                self.emit("}", 1)
                self.emit("return 0;", 1)
                self.emit("}", 0)
                self.emit("", 0)
                return
            uses_seq = any(f.seq for t in sum.types for f in t.fields)
            self.function_head(name, uses_seq)
            self.null_guard()
            self.emit("switch (o->kind) {", 1)
            for t in sum.types:
                self.emit("case %s_kind:" % t.name, 1)
                self.object_fields(t.name, t.fields, "o->v.%s." % t.name, 2)
                if not sum.attributes:
                    self.lit("}")
                self.flush(2)
                self.emit("break;", 2)
            self.emit("default:", 1)
            self.emit('dbuf_putstr(out, "null");', 2)
            self.emit("return 0;", 2)
            self.emit("}", 1)
            if sum.attributes:
                self.emit_attributes_and_close(sum.attributes, "o", 1)
            self.emit("return 0;", 1)
            self.emit("}", 0)
            self.emit("", 0)

        def visitProduct(self, prod, name):
            uses_seq = any(f.seq for f in prod.fields)
            self.function_head(name, uses_seq)
            self.null_guard()
            self.object_fields(name, prod.fields, "o->", 1)
            self.emit_attributes_and_close(prod.attributes, "o", 1)
            self.emit("return 0;", 1)
            self.emit("}", 0)
            self.emit("", 0)

    return SequenceDefVisitor, PrototypeVisitor, FunctionVisitor, JsonVisitor


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("input_file", type=Path)
    ap.add_argument("--header", type=Path, required=True)
    ap.add_argument("--source", type=Path, required=True)
    ap.add_argument("--json", type=Path, required=True)
    args = ap.parse_args()

    asdl, asdl_c = import_cpython_asdl(args.input_file.resolve().parent)
    SeqDef, Proto, Func, Json = make_visitors(asdl, asdl_c)

    mod = asdl.parse(str(args.input_file))
    if not asdl.check(mod):
        sys.exit(1)
    md_visitor = asdl_c.MetadataVisitor()
    md_visitor.visit(mod)
    metadata = md_visitor.metadata

    origin = "/".join(args.input_file.parts[-2:])
    autogen = AUTOGEN_MESSAGE.format(origin)

    with args.header.open("w", newline="\n") as f:
        f.write(autogen)
        f.write(HEADER_PRELUDE)
        asdl_c.ChainOfVisitors(
            asdl_c.TypeDefVisitor(f),
            SeqDef(f),
            asdl_c.StructVisitor(f),
            metadata=metadata,
        ).visit(mod)
        Proto(f, metadata=metadata).visit(mod)
        f.write(HEADER_POSTLUDE)

    with args.source.open("w", newline="\n") as f:
        f.write(autogen)
        f.write(SOURCE_RUNTIME)
        asdl_c.ChainOfVisitors(
            asdl_c.SequenceConstructorVisitor(f),
            metadata=metadata,
        ).visit(mod)
        f.write("/* ---- generated: node constructors ---- */\n\n")
        Func(f, metadata=metadata).visit(mod)

    with args.json.open("w", newline="\n") as f:
        f.write(autogen)
        f.write(JSON_RUNTIME)
        Json(f, metadata).visit(mod)
        f.write(JSON_ENTRY)

    print(f"{args.header}, {args.source}, {args.json} regenerated.")


if __name__ == "__main__":
    main()
