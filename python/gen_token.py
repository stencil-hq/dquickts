#! /usr/bin/env python3
# Derived from CPython Tools/build/generate_token.py (PSF-2.0).
#
# Generates python/token.h (pycore_token.h equivalent) and python/token.c
# (Parser/token.c equivalent) from cpython/Grammar/Tokens.  The table/switch
# generation is CPython's own code (loaded from the checkout); this wrapper
# only adapts the output to dquickts' single translation unit: no Python.h
# includes, no Py_BUILD_CORE guard, and every symbol is `static`.
#
# It also writes python/lexer_unicode.h, the Unicode/codec data the lexer needs
# and that CPython takes from its own runtime: XID_Start/XID_Continue (as
# _PyUnicode_ScanIdentifier uses them), Py_UNICODE_ISPRINTABLE, and the codec
# alias names that resolve to the codecs the string tokenizer supports.  The
# data is taken from the host interpreter, which must be CPython 3.15 so the
# Unicode database matches.
#
# Usage (from the repo root):
#   gen_token.py cpython/Grammar/Tokens python/token.h python/token.c python/lexer_unicode.h

import importlib.util
import os
import sys

SCRIPT_NAME = 'python/gen_token.py'


def load_cpython_generator(root):
    path = os.path.join(root, 'Tools', 'build', 'generate_token.py')
    spec = importlib.util.spec_from_file_location('cpython_generate_token', path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def write_if_changed(path, content):
    try:
        with open(path) as f:
            if f.read() == content:
                return
    except OSError:
        pass
    with open(path, 'w') as f:
        f.write(content)
    print('%s regenerated' % path)


def replace_once(text, old, new):
    if old not in text:
        raise SystemExit('gen_token.py: pattern not found: %r' % old)
    return text.replace(old, new)


def ranges(pred):
    out = []
    start = None
    for c in range(0x110000):
        if pred(c):
            if start is None:
                start = c
        elif start is not None:
            out.append((start, c - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def emit_ranges(name, rs):
    lines = ['static const uint32_t %s[%d][2] = {' % (name, len(rs))]
    for a, b in rs:
        lines.append('    { 0x%04X, 0x%04X },' % (a, b))
    lines.append('};')
    return '\n'.join(lines) + '\n'


def make_unicode_h(path):
    import unicodedata
    from encodings.aliases import aliases
    if sys.version_info[:2] != (3, 15):
        raise SystemExit('gen_token.py: host Python must be 3.15 (Unicode database)')
    xid_start = ranges(lambda c: chr(c).isidentifier())
    xid_continue = ranges(lambda c: ('a' + chr(c)).isidentifier())
    printable = ranges(lambda c: chr(c).isprintable())
    supported = ('utf_8', 'latin_1', 'ascii')
    names = {m: m for m in supported}
    for alias, mod in aliases.items():
        if mod in supported:
            names[alias] = mod
    out = ['/* Auto-generated by %s from the host CPython %s (Unicode %s). */'
           % (SCRIPT_NAME, sys.version.split()[0], unicodedata.unidata_version),
           '/* XID_Start / XID_Continue as used by _PyUnicode_ScanIdentifier, the',
           '   Py_UNICODE_ISPRINTABLE set, and the normalized codec names (see',
           '   encodings.normalize_encoding + encodings.aliases) that resolve to',
           '   the codecs supported by the string tokenizer. */',
           '#ifndef QP_LEXER_UNICODE_H',
           '#define QP_LEXER_UNICODE_H',
           '']
    out.append(emit_ranges('qp_xid_start_ranges', xid_start))
    out.append(emit_ranges('qp_xid_continue_ranges', xid_continue))
    out.append(emit_ranges('qp_printable_ranges', printable))
    out.append('static const struct { const char *name; const char *codec; } qp_codec_names[%d] = {'
               % len(names))
    for alias in sorted(names):
        out.append('    { "%s", "%s" },' % (alias, names[alias]))
    out.append('};')
    out.append('')
    out.append('#endif /* QP_LEXER_UNICODE_H */')
    write_if_changed(path, '\n'.join(out) + '\n')


def main(infile, h_out, c_out, unicode_out):
    root = os.path.dirname(os.path.dirname(os.path.abspath(infile)))
    gen = load_cpython_generator(root)
    tok_names, ERRORTOKEN, string_to_tok = gen.load_tokens(infile)
    n_names = len(tok_names) + 1   # entries of _PyParser_TokenNames incl. "<N_TOKENS>"

    captured = {}

    def capture(path, content):
        captured[path] = content
        return True
    gen.update_file = capture
    gen.make_h(infile, 'H')
    gen.make_c(infile, 'C')

    hdr = captured['H']
    hdr = hdr.replace(gen.AUTO_GENERATED_BY_SCRIPT,
                      'Auto-generated by %s from cpython/Grammar/Tokens.\n'
                      '// Derived from CPython Include/internal/pycore_token.h (PSF-2.0)'
                      % SCRIPT_NAME)
    hdr = replace_once(hdr, '#ifndef Py_BUILD_CORE\n#  error "this header requires Py_BUILD_CORE define"\n#endif\n\n', '')
    hdr = replace_once(hdr, "// Export these 4 symbols for 'test_peg_generator'\n",
                       '/* Defined in token.c (same translation unit). */\n')
    hdr = replace_once(hdr, 'PyAPI_DATA(const char * const) _PyParser_TokenNames[];',
                       'static const char * const _PyParser_TokenNames[%d];' % n_names)
    hdr = hdr.replace('PyAPI_FUNC(int) ', 'static int ')

    src = captured['C']
    src = src.replace(gen.AUTO_GENERATED_BY_SCRIPT,
                      'Auto-generated by %s from cpython/Grammar/Tokens.\n'
                      '   Derived from CPython Parser/token.c (PSF-2.0)' % SCRIPT_NAME)
    src = replace_once(src, '#include "Python.h"\n#include "pycore_token.h"\n\n', '')
    src = replace_once(src, 'const char * const _PyParser_TokenNames[] = {',
                       'static const char * const _PyParser_TokenNames[%d] = {' % n_names)
    src = src.replace('\nint\n_PyToken_', '\nstatic int\n_PyToken_')

    write_if_changed(h_out, hdr)
    write_if_changed(c_out, src)
    make_unicode_h(unicode_out)


if __name__ == '__main__':
    main(*sys.argv[1:])
